#!/usr/bin/env node
/**
 * Regenerates `src/theme/solar-paths.js` from the Solar Bold icon package.
 *
 * Reads `../node_modules/@solar-icons/react/dist/icons/bold/*.mjs` — the web
 * app's `@solar-icons/react` (the worktree root node_modules is a symlink
 * into the original checkout). The `d:` path strings in those files are
 * delimited with backticks, so they are extracted with a backtick match and
 * written out as one export per icon, keyed by the file's base name. Files
 * that are re-exports of other icons (e.g. `chat-dots`) follow the chain so
 * the alias still resolves to a real path.
 *
 * Idempotent: the key list is sorted and the file fully rewritten, so running
 * it a second time changes nothing. Run from `mobile/`.
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const ICON_DIR = path.resolve(here, '../../node_modules/@solar-icons/react/dist/icons/bold');
const OUT = path.resolve(here, '../src/theme/solar-paths.js');

function extractPath(source, file, seen = new Set()) {
  // The Solar files delimit the path with backticks; other quoting styles are
  // matched so a package update does not break the generator silently.
  const backtick = source.match(/d:`([^`]+)`/);
  if (backtick) return backtick[1];

  // Re-export chain: `import { X as Y } from './other.mjs'` — follow it when
  // the target is another icon in the same directory, so alias icons like
  // `chat-dots` resolve to the icon they re-export.
  const reExport = source.match(/from\s*['"]([^'"]+)['"]/);
  if (reExport) {
    const target = path.resolve(path.dirname(file), reExport[1]);
    if (target.startsWith(ICON_DIR + path.sep) && !seen.has(target)) {
      seen.add(target);
      return extractPath(readFileSync(target, 'utf8'), target, seen);
    }
  }

  // Some Solar Bold icons are shapes without a `d` path (circles, ovals).
  // They are skipped rather than written as empty paths: a caller rendering
  // them gets nothing, and a silent "" in solarPaths is a trap for the screens
  // built on top of this.
  console.warn(`Skipping ${path.basename(file)}: no d: path string`);
  return null;
}

const paths = {};
for (const file of readdirSync(ICON_DIR).filter((f) => f.endsWith('.mjs')).sort()) {
  const name = file.slice(0, -'.mjs'.length);
  const d = extractPath(readFileSync(path.join(ICON_DIR, file), 'utf8'), path.join(ICON_DIR, file));
  if (d) paths[name] = d;
}

const lines = Object.keys(paths)
  .sort()
  .map((name) => `  ${JSON.stringify(name)}: ${JSON.stringify(paths[name])},`);

mkdirSync(path.dirname(OUT), { recursive: true });
writeFileSync(
  OUT,
  `// Generated by scripts/gen-icons.mjs — do not edit by hand.\n\nexport const solarPaths = {\n${lines.join('\n')}\n};\n`,
);
console.log(`Wrote ${Object.keys(paths).length} Solar Bold paths to ${path.relative(process.cwd(), OUT)}`);
