import Svg, { Path } from 'react-native-svg';

import { solarPaths } from '../theme/solar-paths.js';
import { useTheme } from '../theme/useTheme.js';
import { tokens } from '../theme/tokens.js';

/**
 * SvgIcon — renders one Solar Bold path as an inline SVG.
 *
 * `d` is the path string; when `color` is omitted the glyph uses the token
 * ink for the resolved theme, so every icon reads as part of the app.
 */
export function SvgIcon({ d, size = 24, color, fillRule = 'evenodd', clipRule = 'evenodd', ...rest }) {
  const t = tokens(useTheme().resolved);
  return (
    <Svg width={size} height={size} viewBox="0 0 24 24" {...rest}>
      <Path d={d} fill={color ?? t.ink} fillRule={fillRule} clipRule={clipRule} />
    </Svg>
  );
}

/**
 * Renders a Solar Bold icon by name from `solarPaths`, generated by
 * `scripts/gen-icons.mjs` — later screens ask for icons as data:
 * `<SolarIcon name="wallet" size={20} />`.
 */
export function SolarIcon({ name, size, color, ...rest }) {
  return <SvgIcon d={solarPaths[name]} size={size} color={color} {...rest} />;
}
